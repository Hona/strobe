/// The primary first, then the secondaries, each metric once.
fn tested(s: &Value) -> Vec<&Value> {
    let mut seen: Vec<&str> = Vec::new();
    let mut rows = Vec::new();
    for c in std::iter::once(&s["primary"]).chain(s["secondaries"].as_array().into_iter().flatten()) {
        let m = c["metric"].as_str().unwrap_or("");
        if m.is_empty() || seen.contains(&m) {
            continue;
        }
        seen.push(m);
        rows.push(c);
    }
    rows
}

/// Descriptive rows not already tested; with `drop_zero`, those that read 0 on both sides go (counted).
fn context(s: &Value, drop_zero: bool) -> (Vec<&Value>, usize) {
    let tested: Vec<&str> = tested(s).iter().filter_map(|c| c["metric"].as_str()).collect();
    let mut seen: Vec<&str> = Vec::new();
    let mut zeros = 0;
    let mut rows = Vec::new();
    for c in s["descriptive"].as_array().into_iter().flatten() {
        let m = c["metric"].as_str().unwrap_or("");
        if m.is_empty() || tested.contains(&m) || seen.contains(&m) {
            continue;
        }
        seen.push(m);
        if drop_zero && f(&c["base"]) == 0.0 && f(&c["head"]) == 0.0 {
            zeros += 1;
            continue;
        }
        rows.push(c);
    }
    (rows, zeros)
}

fn all_rows(s: &Value) -> Vec<&Value> {
    let mut v = tested(s);
    v.extend(context(s, false).0);
    v
}

/// The verdict as a cell says it; `html` inside `<summary>`.
fn verdict_text(c: &Value, o: Out, s: &Value, aa: bool, html: bool) -> String {
    let v = verdict(c);
    let sub = |x: &str| if x.is_empty() { String::new() } else { format!(" <sub>{}</sub>", html_esc(x)) };
    let bold = |x: &str| if html { format!("<b>{}</b>", html_esc(x)) } else { format!("**{}**", cell(x)) };
    match o {
        Out::Better | Out::Worse if !v.starts_with("worse") => bold(v),
        Out::AaFalse => format!("{}{}", bold("false positive"), sub("A/A")),
        Out::Same if aa => format!("same{}", sub(&format!("A/A passed, {}", v.trim_start_matches("same").trim().trim_matches(['(', ')'])))),
        Out::Same => html_esc(v),
        Out::NoWorse | Out::NoWorseSlower | Out::Worse => {
            let (word, rest) = if let Some(r) = v.strip_prefix("no worse") { ("no worse", r) } else { ("worse", v.trim_start_matches("worse")) };
            format!("{}{}", bold(word), sub(rest.trim().trim_matches(['(', ')'])))
        }
        Out::Refused => {
            let (id, why) = refusal(v);
            if html { format!("refused: {}{}", html_esc(&id), sub(&why)) } else { format!("`refused: {id}`{}", sub(&why)) }
        }
        Out::Unclear | Out::Stopped | Out::Saturated => {
            let (word, mut rest) = split_word(v);
            if rest.is_empty()
                && let Some(n) = c["needed_pairs"].as_u64().filter(|n| *n <= 1000)
            {
                rest = format!("~{n} pairs");
            }
            if word == "saturated" {
                rest = rest.split(';').next().unwrap_or("").to_string();
            }
            format!("{}{}", html_esc(&word), sub(&rest))
        }
        Out::Gated => {
            if s["decided"] != true {
                "gated on primary".into()
            } else if f(&c["lo"]) > 0.0 || f(&c["hi"]) < 0.0 {
                let need = s["holm_pairs"].as_u64().filter(|n| *n > s["pairs"].as_u64().unwrap_or(0));
                format!("unconfirmed{}", sub(&need.map(|n| format!("Holm: needs {n} pairs")).unwrap_or_else(|| "Holm".into())))
            } else {
                let need = c["needed_pairs"].as_u64().filter(|n| *n <= 1000).map(|n| format!("~{n} pairs")).unwrap_or_default();
                format!("unclear{}", sub(&need))
            }
        }
        Out::Desc => String::new(),
        Out::NotRun => "not run".into(),
        _ => html_esc(v),
    }
}

fn variants(r: &Value) -> (Value, Value) {
    let find = |role: &str| r["variants"].as_array().into_iter().flatten().find(|v| v["role"] == role).cloned().unwrap_or(Value::Null);
    (find("base"), find("head"))
}

fn local_path(s: &str) -> bool {
    s.starts_with('/') || s.starts_with('\\') || s.starts_with("~") || s.as_bytes().get(1) == Some(&b':') || s.starts_with("./") || s.starts_with("../")
}

/// The commit in a variant's label (`<name>@<sha>…`).
fn label_commit(v: &Value) -> Option<String> {
    let label = v["label"].as_str()?;
    let (_, rest) = label.rsplit_once('@')?;
    let sha: String = rest.chars().take_while(|c| c.is_ascii_hexdigit()).collect();
    (sha.len() >= 7).then_some(sha)
}

/// How a report names a variant in public: `1982f5313f`, `origin/perf-x@7bf4e2d566`, `… (dirty)`;
/// never a local folder's name.
fn tag(v: &Value) -> String {
    let label = v["label"].as_str().unwrap_or("");
    let spec = v["spec"].as_str().unwrap_or("");
    let dirty = v["dirty"] == true || label.ends_with("(dirty)");
    let sha = v["commit"].as_str().map(|c| c.chars().take(10).collect::<String>()).or_else(|| label_commit(v));
    let Some(sha) = sha else { return if local_path(spec) || spec == "." { "working tree".into() } else { spec.to_string() } };
    let is_ref = !spec.is_empty() && spec != "." && !local_path(spec) && !spec.chars().all(|c| c.is_ascii_hexdigit()) && v["kind"] != "dir";
    let mut t = if is_ref { format!("{spec}@{sha}") } else { sha };
    if dirty {
        t += " (dirty)";
    }
    t
}

fn short_cpu(cpu: &str) -> String {
    let mut c = cpu.replace("(R)", "").replace("(TM)", "").replace(" CPU", "");
    if let Some(i) = c.find(" @ ") {
        c.truncate(i);
    }
    let words: Vec<&str> = c.split_whitespace().collect();
    let keep: Vec<&str> = words.iter().copied().filter(|w| !w.ends_with("-Core") && *w != "Processor").collect();
    keep.join(" ")
}

fn short_gpu(g: &str) -> String {
    g.replace("NVIDIA GeForce ", "").replace("NVIDIA ", "").replace("AMD Radeon(TM) ", "Radeon ").replace("(R)", "").replace("(TM)", "")
}

/// `0-15`, `0-7,16-23`: a CPU mask as ranges.
fn cpu_list(mask: u64) -> String {
    let mut parts = Vec::new();
    let mut c = 0;
    while c < 64 {
        if mask >> c & 1 == 1 {
            let start = c;
            while c < 64 && mask >> c & 1 == 1 {
                c += 1;
            }
            parts.push(if c - 1 == start { start.to_string() } else { format!("{start}–{}", c - 1) });
        }
        c += 1;
    }
    parts.join(",")
}

/// The busiest other processes across blocks, `` `bun.exe` 1230% ``.
fn top_procs(blocks: &[&Value], n: usize) -> Vec<String> {
    let mut best: BTreeMap<String, f64> = BTreeMap::new();
    for b in blocks {
        for e in b["background"].as_array().into_iter().flatten() {
            let (Some(name), Some(p)) = (e[0].as_str(), e[1].as_f64()) else { continue };
            let x = best.entry(name.to_string()).or_insert(0.0);
            *x = x.max(p);
        }
    }
    let mut v: Vec<(String, f64)> = best.into_iter().collect();
    v.sort_by(|a, b| b.1.total_cmp(&a.1).then(a.0.cmp(&b.0)));
    v.into_iter().take(n).map(|(name, p)| format!("{} {p:.0}%", code(&name))).collect()
}

/// A series label without the target (`window-closed · tray` → `window-closed`).
fn short_label(label: &str) -> &str {
    label.rsplit_once(" · ").map(|(a, _)| a).unwrap_or(label)
}

/// A warning's text up to its first `: ` detail list, at most `max` characters.
fn first_clause(text: &str, max: usize) -> String {
    let t = text.trim();
    if t.chars().count() <= max {
        return t.to_string();
    }
    let cut: String = t.chars().take(max).collect();
    let at = cut.rfind([';', ',', ' ']).unwrap_or(cut.len());
    format!("{}…", cut[..at].trim_end_matches([',', ';', ' ']))
}

fn thousands(n: usize) -> String {
    let s = n.to_string();
    let mut out = String::new();
    for (i, ch) in s.chars().enumerate() {
        if i > 0 && (s.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(ch);
    }
    out
}

/// A chart value with three significant digits and no trailing zeros.
fn num(v: f64) -> String {
    if !v.is_finite() {
        return "0".into();
    }
    let digits = if v.abs() >= 100.0 {
        0
    } else if v.abs() >= 10.0 {
        1
    } else if v.abs() >= 1.0 {
        2
    } else {
        3
    };
    let s = format!("{v:.digits$}");
    if s.contains('.') { s.trim_end_matches('0').trim_end_matches('.').to_string() } else { s }
}

/// 1, 2, 2.5 or 5 times a power of ten at or above `v`.
fn nice_max(v: f64) -> f64 {
    if v.is_nan() || v <= 0.0 {
        return 1.0;
    }
    let p = 10f64.powf(v.log10().floor());
    [1.0, 1.2, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0, 6.0, 8.0, 10.0].into_iter().map(|m| m * p).find(|x| *x >= v * 1.05).unwrap_or(10.0 * p)
}

/// The chart's unit and the divisor that gets the values into it.
fn chart_unit(unit: &str, max: f64) -> (f64, String) {
    match unit {
        "bytes" if max >= 1024.0 * 1024.0 * 1024.0 => (1024.0 * 1024.0 * 1024.0, "GB".into()),
        "bytes" if max >= 1024.0 * 1024.0 => (1024.0 * 1024.0, "MB".into()),
        "bytes" if max >= 1024.0 => (1024.0, "KB".into()),
        "bytes" => (1.0, "B".into()),
        "" => (1.0, "value".into()),
        u => (1.0, u.to_string()),
    }
}

/// A bisect experiment: the culprit (or what is left) and each step's comparison.
fn bisect(r: &Value) -> String {
    let id = r["id"].as_str().unwrap_or("");
    let file = repo_relative(r["file"].as_str().unwrap_or(""));
    let range = r["range"].as_str().unwrap_or("").split("..").map(|c| c.chars().take(10).collect::<String>()).collect::<Vec<_>>().join("..");
    let mut t = format!("**{}** ({}) · bisect of {} over {}: **{}**\n\n", code(&file), code(id), code(r["metric"].as_str().unwrap_or("")), code(&range), cell(r["verdict"].as_str().unwrap_or("")));
    t += "| Step | Commit (against good) | Pairs | Change [CI] | Outcome |\n|---:|:---|---:|---:|:---|\n";
    for s in r["steps"].as_array().into_iter().flatten() {
        let o = outcome(s, false);
        t += &format!(
            "| {} | {} {} | {} | {} <sub>{}</sub> | {} |\n",
            s["step"],
            code(s["short"].as_str().unwrap_or("")),
            cell(s["subject"].as_str().unwrap_or("")),
            s["pairs"],
            ink(&delta(s, f(&s["estimate"])), tone(s, o), false),
            interval(s),
            cell(verdict(s))
        );
    }
    t + &format!("\n<sub>Each step: <code>strobe report experiment &lt;step experiment&gt; --format pr</code>; this bisect: <code>strobe report experiment {id} --open</code>.</sub>\n")
}
